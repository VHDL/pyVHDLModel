"""This module contains the predefined context ``ieee.ieee_bit_context`` of VHDL library ``IEEE``."""

from pyTooling.Decorators   import export

from pyVHDLModel            import VHDLVersion
from pyVHDLModel.Predefined import PredefinedContext


@export
class Ieee_Bit_Context(PredefinedContext):
	"""
	Predefined context ``ieee.ieee_bit_context`` (IEEE Std 1076-2008, 16.9).

	It makes the declarations of ``ieee.numeric_bit`` visible:

	.. code-block:: VHDL

	   context IEEE_BIT_CONTEXT is
	     library IEEE;
	     use IEEE.NUMERIC_BIT.all;
	   end context IEEE_BIT_CONTEXT;
	"""

	def __init__(self, vhdlVersion: VHDLVersion = VHDLVersion.VHDL2008) -> None:
		"""
		Initializes the ``ieee_bit_context`` context.

		:param vhdlVersion: Optional, the VHDL version of the context items. Default: ``VHDLVersion.VHDL2008``.
		:raises ValueError: If parameter 'vhdlVersion' is None.
		:raises TypeError:  If parameter 'vhdlVersion' is not of type :class:`~pyVHDLModel.VHDLVersion`.
		:raises ValueError: If parameter 'vhdlVersion' is not a supported VHDL version (VHDL-2008).
		"""
		super().__init__(vhdlVersion)

		self._AddLibraryClause(("IEEE", ))
		self._AddPackageClause(("IEEE.NUMERIC_BIT.all", ))
