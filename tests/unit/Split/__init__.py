"""
Split tests: ``Split()`` turns a declaration with an identifier list into one declaration per identifier.

Each test checks the identifiers of the declarations, that the new declarations own copies of the subtype indication
and the default expression, and the parent relation. In a parent, the new declarations follow the split declaration, and
the namespace and lookup tables of an indexed declarative region refer to them.
"""
from typing                      import Iterable

from pyVHDLModel.Base            import ModelEntity
from pyVHDLModel.Formatting.VHDL import VHDLWriter


def _formatted(declarations: Iterable[ModelEntity]) -> list[str]:
	"""The VHDL source of each declaration, as written by the VHDL writer."""
	writer = VHDLWriter()
	return [writer.Format(declaration) for declaration in declarations]
